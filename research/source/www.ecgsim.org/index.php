<p class="text">
ECGSIM is an interactive simulation program that enables one to study the
relationship between the electric activity of the heart
and the resulting potentials on the thorax&#58; PQRST wave forms as well
as body surface potential maps.
</p>
<p class="text">	
It is intended to serve as both an educational and a research tool. In
education its main application is to help students understand the
relation between the activity of the heart and the ECG. The typical
use in research is testing any hypothesis one may have regarding the
manifestation of cardiac malfunctioning in the electrocardiographic
wave forms on the thorax.
<br>
