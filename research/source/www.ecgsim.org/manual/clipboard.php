        <H2>Clipboard</H2>

        <p class="text">
            The clipboard may be used to copy the content from one application to another. In
            ECGSIM, you may copy the content in any of the four panes as an image onto the
            clipboard by pressing <em>&lt;Ctrl&gt;</em><tt>-C</tt> while the mouse is within the
            pane, or by selecting <TT>-Copy-</TT> from the main menu item <tt>-Edit-</tt> and
            then choose the item that corresponds to the pane to copy.
        </P>

        <p class="text">
            From the clipboard the image may be pasted into other applications. However, 
            ECGSIM should still be running at the time that you paste the image. ECGSIM may 
            be minimized during the paste operation.
        </P>
