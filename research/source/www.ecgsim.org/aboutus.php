<h2><a id="adriaan"></a>Adriaan&nbsp;van&nbsp;Oosterom</h2>
<p class="text">

<img src="pictures/verticaal/IMG_8280.jpg" class="adriaan"
alt="Picture of Adriaan van Oosterom" title="Adriaan van Oosterom">

After studying to become an electronic engineer Adriaan van Oosterom
was employed by the Laboratory of Medical Physics at the University of
Amsterdam where, from 1961 to 1965, he was engaged in the designing of
electronic equipment for use in experimental cardiologic research.

<br>

From 1965 to 1971 he studied Experimental Physics at the University of
Amsterdam where, in 1971, he received an honours degree in Physics
&#40;MSc&#41;.

<br>

Next, from 1971 to 1981, he worked at the Laboratory of Medical
Physics &#40;mentor: Prof. Dr. J. Strackee&#41;, as well as at the
Department of Experimental Cardiology &#40;Prof. Dr. D. Durrer&#41;,
both in Amsterdam.

<br>

During this period various physical aspects of the genesis of the
electrocardiogram were studied, which led to a PhD in Physics in 1978
at the University of Amsterdam.

<br>

In 1981 he was appointed Professor of Medical Physics at the
University of Nijmegen. Here he set up a research group studying
Bioelectricity. Besides subjects related to electrocardiography, other
bioelectric phenomena were studied, such as those related to
electroneurography, electromyography, electroencephalography,
functional electrostimulation and electrical impedance tomography.

<br>

In September 2003 he was invited to join the Department of Cardiology
of the Centre Hospitalier Universitaire Vaudois &#40;CHUV&#41;,
Lausanne; Switzerland, where he was subsequently appointed Professor
of Experimental Cardiology. From his base at the Institute of Signal
Processing of the Ecole Polytechnique F&#233;d&#233;rale de Lausanne
&#40;EPFL&#41; he was involved in research on the electric activity of
the heart, with special focus on atrial fibrillation.

<br>

After his retirement in September 2009 van Oosterom returned to the
Netherlands, where he collaborated in scientific projects on the inverse
problem of electrocardiology.

<br>

In April 2019 Adriaan van Oosterom passed away at the age of 77. He
will be dearly missed by his colleagues.
