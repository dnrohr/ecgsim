<h2><a id="thom"></a>Thom&nbsp;Oostendorp</h2>
<p class="text">
<img src="pictures/verticaal/thom.jpg" alt="Picture of Thom Oostendorp" class="thom" title="Thom Oostendorp">
<a href="http://www.mbfys.ru.nl/~thom" target="_blank">Thom Oostendorp</a> is an associate professor at the <a
 href="http://www.ru.nl/donders" target ="_blank">Donders Institute
for Brain, Cognition and Behaviour</a> of the <a href="http://www.ru.nl">Radboud
University</a> in Nijmegen, the Netherlands.
<br>
From 1977 to 1983 he studied Experimental Physics at the Radboud
University in Nijmegen, the Netherlands, where he received his MSc
degree in Physics.
<br>
Thom Oostendorp started his scientific career in 1984 modeling the
fetal ECG at the Department of Medical Physics and Biophysics (mentor:
Adriaan van Oosterom) of the Radboud University Medical Center in
Nijmegen, the Netherlands. In 1989 he received a PhD degree in Medical
Science for this work. Since then, he has been worked at the
Department of Medical Physics and Biophysics, first as a assistant
professor, and since 2003 as a research professor. During this time,
his main research interest has been in bio-electricity, specifically
in solving the forward and inverse problem related to the electric
signals that can be observed at the body surface.
<br>
In 2006, the Department of Medical Physics and Biophysics has been
renamed to Department for Cognitive Neuroscience, and has become
incorporated in the Donders Center for Neuroscience.
<br>
Thom Oostendorp is a principal lecturer at the <a
  href="http://www.umcn.nl/Research" target="_blanck"> Radboud
 University Medical Center</a>, where he teaches students of medicine
 and biomedical science. He was elected "Teacher of the Year" 9
 times between 2006 and 2017. He has developed many computer classes that
 involve computer models of physiological systems. In this capacity,
 as well as his scientific involvement, he has played an active role
 in the development of ECGSIM.
</p>
