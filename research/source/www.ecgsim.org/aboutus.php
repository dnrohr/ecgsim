<h2><a id="peter"></a>Peter&nbsp;van&nbsp;Dam</h2>
<p class="text">
<img src="pictures/verticaal/Peter_van_Dam.jpg" id="petervandam" alt="Picture of Peter van Dam" title="Peter van Dam">
After studying to become an electronic engineer Peter van Dam worked  at the &#39;instrumentele dienst&#39; of the Academic Medical Center Utrecht. Here he was engaged in the designing of electronic equipment and software for use in experimental research.
From 1995 to 2008 he was employed by Medtronic &#40;Maastricht and Arnhem&#41;, working at the software and research departments. Several patents were filed and he received a degree in Natural Sciences &#40;MSc&#41;.
<br>
During the period of 2007 to 2010, he also worked at the Laboratory of Medical Physics of Nijmegen &#40;mentor: Prof. Dr. A. van Oosterom&#41;.
<br>
During this period the inverse procedure, relating body surface signals to the electrical functioning of the heart, was enhanced enabling its clinical application. This research led to a PhD in Medical Science in 2010 at the Radboud University Nijmegen. 
Currently he is involved in the further development and verification of this inverse procedure, bringing it towards a clinical application.
<br>
In 2009 he started a company, Peacs, together with his brother, Eelco van Dam. This company aims to develop open source software for educational and research applications. ECGSIM is the first product.
</p>


